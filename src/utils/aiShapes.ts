import type { StrokePoint } from "@/types";

/**
 * 「假 AI 搭子」的简笔画图纸。
 * 用一支虚构的笔（Pen）把每个词画成能认出来的线条，
 * 坐标一律是 0~1 的归一化值，跟画布尺寸无关。
 */
export interface Pen {
  moveTo: (x: number, y: number) => void;
  lineTo: (x: number, y: number) => void;
  line: (x1: number, y1: number, x2: number, y2: number) => void;
  circle: (cx: number, cy: number, r: number, from?: number, to?: number) => void;
  ellipse: (cx: number, cy: number, rx: number, ry: number) => void;
  poly: (points: [number, number][], closed?: boolean) => void;
  done: () => StrokePoint[][];
}

const TAU = Math.PI * 2;

export function createPen(): Pen {
  const strokes: StrokePoint[][] = [];
  let current: StrokePoint[] = [];
  const pt = (x: number, y: number): StrokePoint => ({
    x: Math.min(0.97, Math.max(0.03, x)),
    y: Math.min(0.97, Math.max(0.03, y)),
  });
  const flush = () => {
    if (current.length > 1) strokes.push(current);
    current = [];
  };
  const arc = (cx: number, cy: number, rx: number, ry: number, from: number, to: number) => {
    flush();
    const steps = 24;
    for (let i = 0; i <= steps; i += 1) {
      const a = from + ((to - from) * i) / steps;
      current.push(pt(cx + Math.cos(a) * rx, cy + Math.sin(a) * ry));
    }
    flush();
  };

  return {
    moveTo(x, y) {
      flush();
      current = [pt(x, y)];
    },
    lineTo(x, y) {
      if (current.length === 0) return;
      current.push(pt(x, y));
    },
    line(x1, y1, x2, y2) {
      flush();
      current = [pt(x1, y1), pt(x2, y2)];
      flush();
    },
    circle(cx, cy, r, from = 0, to = TAU) {
      arc(cx, cy, r, r, from, to);
    },
    ellipse(cx, cy, rx, ry) {
      arc(cx, cy, rx, ry, 0, TAU);
    },
    poly(points, closed = false) {
      flush();
      current = points.map(([x, y]) => pt(x, y));
      if (closed) current.push(pt(points[0][0], points[0][1]));
      flush();
    },
    done() {
      flush();
      return strokes;
    },
  };
}

type Recipe = (pen: Pen) => void;

/** 给太阳画一圈光芒 */
function rays(p: Pen, count = 8): void {
  for (let i = 0; i < count; i += 1) {
    const a = (i / count) * TAU + Math.PI / count;
    p.line(0.5 + Math.cos(a) * 0.2, 0.5 + Math.sin(a) * 0.2, 0.5 + Math.cos(a) * 0.3, 0.5 + Math.sin(a) * 0.3);
  }
}

